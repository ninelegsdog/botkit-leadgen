def manager_stats(taken: object) -> str:
    """Личная статистика менеджера: сколько лидов закрыто."""
    return f"📊 Ваша статистика:\nЗакрытых лидов: {taken}"


def admin_stats(
    day_new: object,
    day_taken: object,
    day_closed: object,
    week_new: object,
    week_taken: object,
    week_closed: object,
) -> str:
    """Статистика администратора за день и неделю."""
    return (
        f"📊 Статистика:\n\nСегодня:\n  Новых: {day_new}\n"
        f"  В работе: {day_taken}\n  Закрытых: {day_closed}\n\n"
        f"За неделю:\n  Новых: {week_new}\n"
        f"  В работе: {week_taken}\n  Закрытых: {week_closed}"
    )
